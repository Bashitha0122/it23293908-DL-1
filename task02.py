import pandas as pd

# Load the dataset
df = pd.read_csv('/content/Au_nanoparticle_dataset.csv')

# Create a new DataFrame by filtering the specified columns
filtered_df = df[['N_total', 'N_bulk', 'N_surface', 'R_avg']]

# Display the head of the new dataframe to verify
print(filtered_df.head())

print(filtered_df.head(20))

description_stats = filtered_df[['N_total', 'N_bulk', 'N_surface', 'R_avg']].describe()
print(description_stats)

import matplotlib.pyplot as plt
import seaborn as sns

features = ['N_total', 'N_bulk', 'N_surface', 'R_avg']

fig, axes = plt.subplots(1, 4, figsize=(20, 5))

for i, feature in enumerate(features):
    sns.histplot(filtered_df[feature], kde=True, ax=axes[i])
    axes[i].set_title(f'Histogram of {feature}')
    axes[i].set_xlabel(feature)
    axes[i].set_ylabel('Frequency')

plt.tight_layout()
plt.show()

import seaborn as sns
