import seaborn as sns
import matplotlib.pyplot as plt

# 'filtered_df' is the dataframe containing only the 4 features
g = sns.PairGrid(filtered_df)

# Plots on the upper half: bivariate histogram
g.map_upper(sns.histplot)

# Plots on the diagonal: histogram of each feature along with the kernel density estimation plot
g.map_diag(sns.histplot, kde=True)

# Plots on the lower half: bivariate kernel density estimation plot
g.map_lower(sns.kdeplot)

plt.suptitle('Pairplot: Hist/KDE Diag, Bivariate Hist Upper, Bivariate KDE Lower', y=1.02)
plt.show()